bool _registered = false;
Locale legacyDisplayLocale = const Locale('zh');

void registerLegacyTranslations() {
  if (_registered) return;
  _registered = true;
  JobsDemoStrings.registerTranslations(legacyTranslations);
  JobsDemoStrings.registerTranslations(legacyCatalogTitles);
}

String legacyUiText(BuildContext context, String value) {
  legacyDisplayLocale = Localizations.localeOf(context);
  return legacyUiTextForLocale(legacyDisplayLocale, value);
}

String legacyUiTextForLocale(Locale locale, String value, {int depth = 0}) {
  if (depth > 8) return value;
  registerLegacyTranslations();
  final strings = JobsDemoStrings(locale);
  final direct = strings.text(value);
  if (direct != value) return direct;
  final trimmed = value.trim();
  final clean = strings.text(trimmed);
  if (clean != trimmed) return clean;
  for (final key in legacyTranslations.keys.where((e) => e.contains('{0}'))) {
    final pattern = RegExp(
      '^' +
          RegExp.escape(key)
              .replaceAllMapped(RegExp(r'\\\{([0-9]+)\\\}'), (_) => '(.*?)') +
          r'$',
      dotAll: true,
    );
    final match = pattern.firstMatch(value);
    if (match == null) continue;
    var translated = strings.text(key);
    for (var i = 1; i <= match.groupCount; i++) {
      translated = translated.replaceAll(
        '{${i - 1}}',
        legacyUiTextForLocale(locale, match.group(i) ?? '', depth: depth + 1),
      );
    }
    return translated;
  }
  return value;
}

/// 翻译界面文案；数值、用户输入与示例代码保留原值。
class LegacyText extends StatelessWidget {
  const LegacyText(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.semanticsIdentifier,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  });
  final String data;
  final TextStyle? style;
  final StrutStyle? strutStyle;
  final TextAlign? textAlign;
  final TextDirection? textDirection;
  final Locale? locale;
  final bool? softWrap;
  final TextOverflow? overflow;
  final TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel, semanticsIdentifier;
  final TextWidthBasis? textWidthBasis;
  final TextHeightBehavior? textHeightBehavior;
  final Color? selectionColor;
  @override
  Widget build(BuildContext context) => Text(
    legacyUiText(context, data),
    style: style,
    strutStyle: strutStyle,
    textAlign: textAlign,
    textDirection: textDirection,
    locale: locale,
    softWrap: softWrap,
    overflow: overflow,
    textScaler: textScaler,
    maxLines: maxLines,
    semanticsLabel: semanticsLabel,
    semanticsIdentifier: semanticsIdentifier,
    textWidthBasis: textWidthBasis,
    textHeightBehavior: textHeightBehavior,
    selectionColor: selectionColor,
  );
}

String legacyControlLabel(BuildContext context, String value) =>
    legacyUiText(context, value);
String legacyControlLabelFallback(String value) =>
    legacyUiTextForLocale(legacyDisplayLocale, value);
InputDecoration legacyInputDecoration(
  BuildContext context,
  InputDecoration value,
) => value.copyWith(
  labelText: value.labelText == null
      ? null
      : legacyUiText(context, value.labelText!),
  hintText: value.hintText == null
      ? null
      : legacyUiText(context, value.hintText!),
  helperText: value.helperText == null
      ? null
      : legacyUiText(context, value.helperText!),
  errorText: value.errorText == null
      ? null
      : legacyUiText(context, value.errorText!),
  counterText: value.counterText == null
      ? null
      : legacyUiText(context, value.counterText!),
);
InputDecoration legacyInputDecorationFallback(InputDecoration value) =>
    value.copyWith(
      labelText: value.labelText == null
          ? null
          : legacyControlLabelFallback(value.labelText!),
      hintText: value.hintText == null
          ? null
          : legacyControlLabelFallback(value.hintText!),
      helperText: value.helperText == null
          ? null
          : legacyControlLabelFallback(value.helperText!),
      errorText: value.errorText == null
          ? null
          : legacyControlLabelFallback(value.errorText!),
    );

