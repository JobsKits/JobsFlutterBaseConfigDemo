      locale.languageCode == 'zh' &&
          (locale.scriptCode == 'Hant' ||
              locale.countryCode == 'TW' ||
              locale.countryCode == 'HK')
      ? 'zh-Hant'
      : locale.languageCode;
  final index = const [
    'zh',
    'zh-Hant',
    'bo',
    'en',
    'ja',
    'fr',
    'es',
    'de',
    'ru',
    'ko',
  ].indexOf(code);
  final row = workflowTranslations[key];
